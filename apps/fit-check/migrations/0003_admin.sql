-- The admin app (apps/admin): sign-in sessions, Ryan's full skill answers, one name per skill for trends,
-- and where each posting came from. See apps/admin/README.md.

-- Who pasted the posting: a site visitor, or Ryan through the admin app's "Add posting" box.
ALTER TABLE fit_checks ADD COLUMN source TEXT NOT NULL DEFAULT 'visitor' CHECK (source IN ('visitor', 'ryan'));

-- Admin sign-in sessions. The cookie holds a random token; only its SHA-256 is stored.
CREATE TABLE admin_sessions (
  id TEXT PRIMARY KEY, -- sha256 of the cookie's token
  github_id INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  expires_at TEXT NOT NULL
);
CREATE INDEX admin_sessions_expires_at ON admin_sessions (expires_at);

-- Ryan's answer to a skill question, in full. The Worker reads skill_answers (have / learning / not_pursuing), which
-- the admin app writes alongside this where an answer fits; "close" and "dont_have" wait here until the Worker
-- learns them (docs/fit-check-flow.md#the-skills-check).
CREATE TABLE skill_responses (
  skill_key TEXT PRIMARY KEY, -- same key as skill_questions and skill_answers
  skill TEXT NOT NULL,
  answer TEXT NOT NULL CHECK (answer IN ('have', 'close', 'learning', 'dont_have', 'not_pursuing')),
  evidence_kind TEXT CHECK (evidence_kind IN ('job', 'project', 'education', 'certificate', 'testimonial', 'self_taught')),
  evidence_id TEXT, -- an id from apps/fit-check/src/record.json
  close_to TEXT, -- for "close": the skill or experience Ryan has instead
  note TEXT,
  -- Adding confirmed skills to data/resume.yaml by pull request isn't built yet.
  resume_status TEXT NOT NULL DEFAULT 'todo' CHECK (resume_status IN ('todo', 'not_needed', 'done')),
  answered_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- One display name per skill, and every variant seen in a posting as an alias of it. Trends count by skill id.
CREATE TABLE skills (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE COLLATE NOCASE,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE TABLE skill_aliases (
  alias TEXT PRIMARY KEY, -- the tidied, lowercased variant (cleanSkill in apps/admin/src/lib/skill-names.ts)
  skill_id INTEGER NOT NULL REFERENCES skills (id),
  source TEXT NOT NULL CHECK (source IN ('seed', 'code', 'jev', 'ryan')), -- who matched it
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX skill_aliases_skill_id ON skill_aliases (skill_id);

